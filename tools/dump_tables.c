/* Table dumper: links against upstream sources and prints all static
 * tables as Crystal literals. Run via tools/gen_tables.sh; output goes
 * to src/brotli/tables_data.cr (+ raw dictionary to dump path).
 */

#include <stdio.h>
#include <stdint.h>

#include "../upstream/brotli/c/common/constants.h"
#include "../upstream/brotli/c/common/context.h"
#include "../upstream/brotli/c/common/dictionary.h"
#include "../upstream/brotli/c/common/transform.h"
#include "../upstream/brotli/c/dec/prefix.h"

static void dump_bytes(const char *name, const uint8_t *p, size_t n) {
  printf("  %s = Bytes[\n", name);
  for (size_t i = 0; i < n; ++i) {
    printf("%u,%s", p[i], (i % 16 == 15 || i + 1 == n) ? "\n" : " ");
  }
  printf("  ]\n\n");
}

int main(int argc, char **argv) {
  FILE *dict_dump = NULL;
  if (argc > 1) {
    dict_dump = fopen(argv[1], "wb");
    if (!dict_dump) { perror(argv[1]); return 3; }
  }

  /* BROTLI_STATIC_INIT defaults to NONE: kCmdLut is embedded, no init call. */

  printf("# GENERATED by tools/dump_tables.c from upstream/brotli %s\n",
         "42a2ed4 — DO NOT EDIT\n\n");
  printf("require \"./types\"\n\n");
  printf("module Brotli\n");

  dump_bytes("CONTEXT_LOOKUP", _kBrotliContextLookupTable, 2048);

  printf("  # _kBrotliPrefixCodeRanges: [offset, nbits] per block-length symbol\n");
  printf("  PREFIX_CODE_RANGES = [\n");
  for (int i = 0; i < BROTLI_NUM_BLOCK_LEN_SYMBOLS; ++i) {
    printf("    {%u, %u},\n", _kBrotliPrefixCodeRanges[i].offset,
           (unsigned)_kBrotliPrefixCodeRanges[i].nbits);
  }
  printf("  ]\n\n");

  const BrotliTransforms *t = BrotliGetTransforms();
  dump_bytes("TRANSFORM_PREFIX_SUFFIX", t->prefix_suffix, t->prefix_suffix_size);
  printf("  TRANSFORM_PREFIX_SUFFIX_MAP = [\n");
  for (uint32_t i = 0; i < 50; ++i) {
    printf("%u,%s", t->prefix_suffix_map[i], (i % 10 == 9 || i == 49) ? "\n" : " ");
  }
  printf("  ]\n\n");
  dump_bytes("TRANSFORMS_DATA", t->transforms, t->num_transforms * 3);
  printf("  TRANSFORM_CUT_OFF = [\n");
  for (int i = 0; i <= 9; ++i) printf("    %d,\n", t->cutOffTransforms[i]);
  printf("  ]\n\n");

  printf("  # kCmdLut (BrotliDecoderInitCmdLut)\n");
  printf("  CMD_LUT = [\n");
  for (int i = 0; i < BROTLI_NUM_COMMAND_SYMBOLS; ++i) {
    printf("    CmdLut.new(%u, %u, %d, %u, %u, %u),\n",
           kCmdLut[i].insert_len_extra_bits, kCmdLut[i].copy_len_extra_bits,
           kCmdLut[i].distance_code, kCmdLut[i].context,
           kCmdLut[i].insert_len_offset, kCmdLut[i].copy_len_offset);
  }
  printf("  ]\n\n");

  const BrotliDictionary *d = BrotliGetDictionary();
  printf("  DICTIONARY_SIZE_BITS_BY_LENGTH = Bytes[\n");
  for (int i = 0; i < 32; ++i) {
    printf("%u,%s", d->size_bits_by_length[i], (i % 16 == 15 || i == 31) ? "\n" : " ");
  }
  printf("  ]\n\n");
  printf("  DICTIONARY_OFFSETS_BY_LENGTH = [\n");
  for (int i = 0; i < 32; ++i) {
    printf("%u,%s", d->offsets_by_length[i], (i % 8 == 7 || i == 31) ? "\n" : " ");
  }
  printf("  ]\n\n");
  printf("  DICTIONARY_DATA_SIZE = %zu\n", d->data_size);

  if (dict_dump) {
    fwrite(d->data, 1, d->data_size, dict_dump);
    fclose(dict_dump);
  }

  printf("end\n");
  return 0;
}
