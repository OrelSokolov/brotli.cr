/* Table dumper: links against upstream sources and prints all static
 * tables as Crystal literals. Run via tools/gen_tables.sh; output goes
 * to src/brotli/tables_data.cr (+ raw dictionary to dump path, + encoder
 * tables to argv[2] if given -> src/brotli/enc/enc_tables_data.cr).
 */

#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

