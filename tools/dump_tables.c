static void dump_bytes(const char *name, const uint8_t *p, size_t n) {
  printf("  %s = Bytes[\n", name);
  for (size_t i = 0; i < n; ++i) {
    printf("%u,%s", p[i], (i % 16 == 15 || i + 1 == n) ? "\n" : " ");
  }
  printf("  ]\n\n");
}

/* ---- encoder tables (base64 blobs + literal arrays) ---- */

static uint64_t fnv1a64(const uint8_t *p, size_t n) {
  uint64_t h = 14695981039346656037ULL;
  for (size_t i = 0; i < n; ++i) {
    h ^= p[i];
    h *= 1099511628211ULL;
  }
  return h;
}

static void dump_b64(FILE *f, const uint8_t *p, size_t n) {
  static const char enc[] =
      "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  size_t i = 0;
  for (; i + 2 < n; i += 3) {
    uint32_t v = (uint32_t)p[i] << 16 | (uint32_t)p[i + 1] << 8 | p[i + 2];
    putc(enc[(v >> 18) & 63], f);
    putc(enc[(v >> 12) & 63], f);
    putc(enc[(v >> 6) & 63], f);
    putc(enc[v & 63], f);
  }
  if (n - i == 1) {
    uint32_t v = (uint32_t)p[i] << 16;
    putc(enc[(v >> 18) & 63], f);
    putc(enc[(v >> 12) & 63], f);
    fputs("==", f);
  } else if (n - i == 2) {
    uint32_t v = (uint32_t)p[i] << 16 | (uint32_t)p[i + 1] << 8;
    putc(enc[(v >> 18) & 63], f);
    putc(enc[(v >> 12) & 63], f);
    putc(enc[(v >> 6) & 63], f);
    putc('=', f);
  }
}

/* Emits `NAME_RAW = Base64.decode("...")` plus FNV checksum comment. */
static void dump_blob(FILE *f, const char *raw_name, const char *comment,
                      const uint8_t *p, size_t n) {
  fprintf(f, "  # %s (FNV-1a64 = 0x%016llx)\n", comment,
          (unsigned long long)fnv1a64(p, n));
  fprintf(f, "  %s = Base64.decode(\"", raw_name);
  dump_b64(f, p, n);
  fprintf(f, "\")\n\n");
}

static uint8_t *le16_buf(const uint16_t *p, size_t n) {
  uint8_t *b = (uint8_t *)malloc(n * 2);
  if (!b) abort();
  for (size_t i = 0; i < n; ++i) {
    b[2 * i] = (uint8_t)(p[i] & 0xFF);
    b[2 * i + 1] = (uint8_t)(p[i] >> 8);
  }
  return b;
}

static void dump_u8_lit(FILE *f, const char *name, const uint8_t *p, size_t n) {
  fprintf(f, "  %s = Bytes[\n", name);
  for (size_t i = 0; i < n; ++i) {
    fprintf(f, "%u,%s", p[i], (i % 32 == 31 || i + 1 == n) ? "\n" : " ");
  }
  fprintf(f, "  ]\n\n");
}

static void dump_u16_lit(FILE *f, const char *name, const uint16_t *p,
                         size_t n) {
  fprintf(f, "  %s = Slice[\n", name);
  for (size_t i = 0; i < n; ++i) {
    fprintf(f, "%u_u16,%s", p[i], (i % 24 == 23 || i + 1 == n) ? "\n" : " ");
  }
  fprintf(f, "  ]\n\n");
}

static void dump_u32_lit(FILE *f, const char *name, const uint32_t *p,
                         size_t n) {
  fprintf(f, "  %s = Slice[\n", name);
  for (size_t i = 0; i < n; ++i) {
    fprintf(f, "%u_u32,%s", p[i], (i % 16 == 15 || i + 1 == n) ? "\n" : " ");
  }
  fprintf(f, "  ]\n\n");
}

static void dump_u64_lit(FILE *f, const char *name, const uint64_t *p,
                         size_t n) {
  fprintf(f, "  %s = Slice[\n", name);
  for (size_t i = 0; i < n; ++i) {
    fprintf(f, "%llu_u64,%s", (unsigned long long)p[i],
            (i % 8 == 7 || i + 1 == n) ? "\n" : " ");
  }
  fprintf(f, "  ]\n\n");
}

static void dump_enc_tables(FILE *f) {
  fprintf(f, "# GENERATED by tools/dump_tables.c from upstream/brotli %s\n",
          "42a2ed4 — DO NOT EDIT\n\n");
  fprintf(f, "require \"base64\"\n\n");
  fprintf(f, "module Brotli\n  module Enc\n\n");

  fprintf(f, "  # c/enc/dictionary_hash.h: bucket = Hash14*2 + (len < 8);\n"
             "  # one word per bucket, first writer (longest len) wins.\n");
  fprintf(f, "  NUM_HASH_BUCKETS = %d\n\n", BROTLI_ENC_NUM_HASH_BUCKETS);
  {
    uint8_t *w = le16_buf(kStaticDictionaryHashWords,
                          BROTLI_ENC_NUM_HASH_BUCKETS);
    dump_blob(f, "DICT_HASH_WORDS_RAW", "kStaticDictionaryHashWords (LE u16)",
              w, BROTLI_ENC_NUM_HASH_BUCKETS * 2);
    fprintf(f, "  DICT_HASH_WORDS = le_u16(DICT_HASH_WORDS_RAW)\n\n");
    free(w);
  }
  dump_blob(f, "DICT_HASH_LENGTHS", "kStaticDictionaryHashLengths",
            kStaticDictionaryHashLengths, BROTLI_ENC_NUM_HASH_BUCKETS);

  fprintf(f, "  # c/enc/static_dict_lut.h: buckets = Hash15, words packed\n"
             "  # as {len (bit7 = end of bucket), transform, idx} columns.\n");
  fprintf(f, "  NUM_DICT_LUT_BUCKETS = %d\n",
          BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS);
  fprintf(f, "  NUM_DICT_LUT_ITEMS = %d\n\n",
          BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS);
  {
    uint8_t *len = (uint8_t *)malloc(BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS);
    uint8_t *tr = (uint8_t *)malloc(BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS);
    uint16_t *idx = (uint16_t *)malloc(
        BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS * sizeof(uint16_t));
    uint8_t *idx_le;
    if (!len || !tr || !idx) abort();
    for (size_t i = 0; i < BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS; ++i) {
      len[i] = kStaticDictionaryWords[i].len;
      tr[i] = kStaticDictionaryWords[i].transform;
      idx[i] = kStaticDictionaryWords[i].idx;
    }
    dump_blob(f, "STATIC_DICTIONARY_BUCKETS_RAW",
              "kStaticDictionaryBuckets (LE u16)",
              (idx_le = le16_buf(kStaticDictionaryBuckets,
                                 BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS)),
              BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS * 2);
    free(idx_le);
    fprintf(f,
            "  STATIC_DICTIONARY_BUCKETS = "
            "le_u16(STATIC_DICTIONARY_BUCKETS_RAW)\n\n");
    dump_blob(f, "STATIC_DICTIONARY_WORDS_LEN",
              "kStaticDictionaryWords[*].len", len,
              BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS);
    dump_blob(f, "STATIC_DICTIONARY_WORDS_TRANSFORM",
              "kStaticDictionaryWords[*].transform", tr,
              BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS);
    dump_blob(f, "STATIC_DICTIONARY_WORDS_IDX_RAW",
              "kStaticDictionaryWords[*].idx (LE u16)",
              (idx_le = le16_buf(idx, BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS)),
              BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS * 2);
    free(idx_le);
    fprintf(f,
            "  STATIC_DICTIONARY_WORDS_IDX = "
            "le_u16(STATIC_DICTIONARY_WORDS_IDX_RAW)\n\n");
    free(len);
    free(tr);
    free(idx);
  }

  fprintf(f, "  # c/enc/entropy_encode_static.h: fixed codes for q <= 2.\n");
  dump_u8_lit(f, "CODE_LENGTH_DEPTH", kCodeLengthDepth, 18);
  dump_u32_lit(f, "CODE_LENGTH_BITS", kCodeLengthBits, 18);
  dump_u8_lit(f, "STATIC_COMMAND_CODE_DEPTH", kStaticCommandCodeDepth,
              BROTLI_NUM_COMMAND_SYMBOLS);
  dump_u16_lit(f, "STATIC_COMMAND_CODE_BITS", kStaticCommandCodeBits,
               BROTLI_NUM_COMMAND_SYMBOLS);
  dump_u8_lit(f, "STATIC_DISTANCE_CODE_DEPTH", kStaticDistanceCodeDepth, 64);
  dump_u16_lit(f, "STATIC_DISTANCE_CODE_BITS", kStaticDistanceCodeBits, 64);
  dump_u64_lit(f, "ZERO_REPS_BITS", kZeroRepsBits,
               BROTLI_NUM_COMMAND_SYMBOLS);
  dump_u32_lit(f, "ZERO_REPS_DEPTH", kZeroRepsDepth,
               BROTLI_NUM_COMMAND_SYMBOLS);
  dump_u64_lit(f, "NON_ZERO_REPS_BITS", kNonZeroRepsBits,
               BROTLI_NUM_COMMAND_SYMBOLS);
  dump_u32_lit(f, "NON_ZERO_REPS_DEPTH", kNonZeroRepsDepth,
               BROTLI_NUM_COMMAND_SYMBOLS);

  fprintf(f, "  # FNV-1a64 of every blob, verified by spec/enc_tables_spec\n");
  fprintf(f, "  TABLE_CHECKSUMS = {\n");
  fprintf(f, "    DICT_HASH_WORDS_RAW => 0x%016llx_u64,\n",
          (unsigned long long)fnv1a64(
              le16_buf(kStaticDictionaryHashWords, 32768), 32768 * 2));
  fprintf(f, "    DICT_HASH_LENGTHS => 0x%016llx_u64,\n",
          (unsigned long long)fnv1a64(kStaticDictionaryHashLengths, 32768));
  fprintf(f, "    STATIC_DICTIONARY_BUCKETS_RAW => 0x%016llx_u64,\n",
          (unsigned long long)fnv1a64(
              le16_buf(kStaticDictionaryBuckets, 32768), 32768 * 2));
  {
    size_t n = BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS;
    uint8_t *len = (uint8_t *)malloc(n);
    uint8_t *tr = (uint8_t *)malloc(n);
    uint16_t *idx = (uint16_t *)malloc(n * sizeof(uint16_t));
    uint8_t *idx_le;
    if (!len || !tr || !idx) abort();
    for (size_t i = 0; i < n; ++i) {
      len[i] = kStaticDictionaryWords[i].len;
      tr[i] = kStaticDictionaryWords[i].transform;
      idx[i] = kStaticDictionaryWords[i].idx;
    }
    fprintf(f, "    STATIC_DICTIONARY_WORDS_LEN => 0x%016llx_u64,\n",
            (unsigned long long)fnv1a64(len, n));
    fprintf(f, "    STATIC_DICTIONARY_WORDS_TRANSFORM => 0x%016llx_u64,\n",
            (unsigned long long)fnv1a64(tr, n));
    fprintf(f, "    STATIC_DICTIONARY_WORDS_IDX_RAW => 0x%016llx_u64,\n",
            (unsigned long long)fnv1a64(
                (idx_le = le16_buf(idx, n)), n * 2));
    free(idx_le);
    free(len);
    free(tr);
    free(idx);
  }
  fprintf(f, "  }\n\n");

  fprintf(f, "  private def self.le_u16(b : Bytes) : Slice(UInt16)\n"
             "    Slice(UInt16).new(b.size // 2) do |i|\n"
             "      b.unsafe_fetch(i &* 2).to_u16 |\n"
             "        (b.unsafe_fetch(i &* 2 &+ 1).to_u16 << 8)\n"
             "    end\n"
             "  end\n\n");
  fprintf(f, "  end\nend\n");
}

int main(int argc, char **argv) {
  FILE *dict_dump = NULL;
  if (argc > 1) {
    dict_dump = fopen(argv[1], "wb");
    if (!dict_dump) { perror(argv[1]); return 3; }
  }
  FILE *enc_dump = NULL;
  if (argc > 2) {
    enc_dump = fopen(argv[2], "wb");
    if (!enc_dump) { perror(argv[2]); return 3; }
  }

  /* BROTLI_STATIC_INIT defaults to NONE: kCmdLut is embedded, no init call. */

  printf("# GENERATED by tools/dump_tables.c from upstream/brotli %s\n",
         "42a2ed4 — DO NOT EDIT\n\n");
  printf("require \"./types\"\n\n");
  printf("module Brotli\n");

  dump_bytes("CONTEXT_LOOKUP", _kBrotliContextLookupTable, 2048);

  printf("  # _kBrotliPrefixCodeRanges: [offset, nbits] per block-length symbol\n");
  printf("  PREFIX_CODE_RANGES = [\n");
  for (int i = 0; i < BROTLI_NUM_BLOCK_LEN_SYMBOLS; ++i) {
    printf("    {%u, %u},\n", _kBrotliPrefixCodeRanges[i].offset,
           (unsigned)_kBrotliPrefixCodeRanges[i].nbits);
  }
  printf("  ]\n\n");

  const BrotliTransforms *t = BrotliGetTransforms();
  dump_bytes("TRANSFORM_PREFIX_SUFFIX", t->prefix_suffix, t->prefix_suffix_size);
  printf("  TRANSFORM_PREFIX_SUFFIX_MAP = [\n");
  for (uint32_t i = 0; i < 50; ++i) {
    printf("%u,%s", t->prefix_suffix_map[i], (i % 10 == 9 || i == 49) ? "\n" : " ");
  }
  printf("  ]\n\n");
  dump_bytes("TRANSFORMS_DATA", t->transforms, t->num_transforms * 3);
  printf("  TRANSFORM_CUT_OFF = [\n");
  for (int i = 0; i <= 9; ++i) printf("    %d,\n", t->cutOffTransforms[i]);
  printf("  ]\n\n");

  printf("  # kCmdLut (BrotliDecoderInitCmdLut)\n");
  printf("  CMD_LUT = [\n");
  for (int i = 0; i < BROTLI_NUM_COMMAND_SYMBOLS; ++i) {
    printf("    CmdLut.new(%u, %u, %d, %u, %u, %u),\n",
           kCmdLut[i].insert_len_extra_bits, kCmdLut[i].copy_len_extra_bits,
           kCmdLut[i].distance_code, kCmdLut[i].context,
           kCmdLut[i].insert_len_offset, kCmdLut[i].copy_len_offset);
  }
  printf("  ]\n\n");

  const BrotliDictionary *d = BrotliGetDictionary();
  printf("  DICTIONARY_SIZE_BITS_BY_LENGTH = Bytes[\n");
  for (int i = 0; i < 32; ++i) {
    printf("%u,%s", d->size_bits_by_length[i], (i % 16 == 15 || i == 31) ? "\n" : " ");
  }
  printf("  ]\n\n");
  printf("  DICTIONARY_OFFSETS_BY_LENGTH = [\n");
  for (int i = 0; i < 32; ++i) {
    printf("%u,%s", d->offsets_by_length[i], (i % 8 == 7 || i == 31) ? "\n" : " ");
  }
  printf("  ]\n\n");
  printf("  DICTIONARY_DATA_SIZE = %zu\n", d->data_size);

  if (dict_dump) {
    fwrite(d->data, 1, d->data_size, dict_dump);
    fclose(dict_dump);
  }

  printf("end\n");

  if (enc_dump) {
    dump_enc_tables(enc_dump);
    fclose(enc_dump);
  }
  return 0;
}
