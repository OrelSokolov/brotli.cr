#!/bin/sh
# Regenerate src/brotli/tables_data.cr and src/brotli/dictionary_data.cr
# from the pinned upstream sources. Requires cc + base64.
set -e
cd "$(dirname "$0")/.."

cc -O2 -o tmp_c/dump_tables tools/dump_tables.c \
  upstream/brotli/c/dec/prefix.c upstream/brotli/c/common/*.c \
  upstream/brotli/c/enc/dictionary_hash.c \
  upstream/brotli/c/enc/static_dict_lut.c \
  -Iupstream/brotli/c -Iupstream/brotli/c/include -lm

mkdir -p src/brotli/enc
./tmp_c/dump_tables tmp_c/dictionary.bin src/brotli/enc/enc_tables_data.cr \
  > src/brotli/tables_data.cr

{
  echo '# GENERATED by tools/gen_tables.sh (dictionary.bin -> base64) — DO NOT EDIT'
  echo
  echo 'require "base64"'
  echo
  echo 'module Brotli'
  echo '  # RFC 7932 Appendix A static dictionary (122784 bytes).'
  printf '  DICTIONARY_DATA = Base64.decode(%s\n' '"'
  base64 -w 76 tmp_c/dictionary.bin
  printf '%s)\n' '"'
  echo 'end'
} > src/brotli/dictionary_data.cr

echo "context:  $(wc -c < src/brotli/tables_data.cr) bytes, dict: $(wc -c < src/brotli/dictionary_data.cr) bytes, enc: $(wc -c < src/brotli/enc/enc_tables_data.cr) bytes"
